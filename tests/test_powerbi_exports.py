"""Power BI exports: the five CSVs the dashboard loads exist, have the columns the semantic
model expects, and their totals match the analysis.

The CSVs are generated by notebook 03 and are not in the repo or the zip (fact_sales.csv is
about 110 MB), so these tests are skipped when the files are absent.
"""
import re

import pandas as pd
import pytest

from src import analysis as an

from conftest import POWERBI_MISSING, SEMANTIC_MODEL_TABLES

EXPORTS = ["fact_sales", "monthly_kpis", "cohort_retention", "rfm_customers", "segment_summary"]

pytestmark = pytest.mark.skipif(
    not all((an.POWERBI_DIR / f"{name}.csv").exists() for name in EXPORTS), reason=POWERBI_MISSING)


def model_columns(table: str) -> tuple[list[str], int, str]:
    """Source columns, Csv.Document column count and file name of a table in the semantic model."""
    tmdl = (SEMANTIC_MODEL_TABLES / f"{table}.tmdl").read_text(encoding="utf-8")
    columns = re.findall(r"sourceColumn: (\S+)", tmdl)
    count = int(re.search(r"Columns=(\d+)", tmdl).group(1))
    file_name = re.search(r'File\.Contents\("[^"]*\\([^\\"]+)"\)', tmdl).group(1)
    return columns, count, file_name


def read_export(name: str, **kwargs) -> pd.DataFrame:
    return pd.read_csv(an.POWERBI_DIR / f"{name}.csv", **kwargs)


@pytest.fixture(scope="module")
def fact_sales() -> pd.DataFrame:
    return read_export("fact_sales", usecols=["date", "invoice", "customer_id", "line_revenue",
                                              "is_cancelled", "has_customer", "is_fully_cancelled_order"],
                       dtype={"invoice": str})


@pytest.fixture(scope="module")
def monthly() -> pd.DataFrame:
    return read_export("monthly_kpis", parse_dates=["month"])


@pytest.fixture(scope="module")
def rfm_customers() -> pd.DataFrame:
    return read_export("rfm_customers")


@pytest.fixture(scope="module")
def segments() -> pd.DataFrame:
    return read_export("segment_summary")


# ---------- files and columns ----------

@pytest.mark.parametrize("name", EXPORTS)
def test_export_has_the_columns_the_model_expects(name):
    columns, count, file_name = model_columns(name)
    assert file_name == f"{name}.csv"
    header = list(read_export(name, nrows=0).columns)
    assert header == columns
    assert len(header) == count


# ---------- fact_sales ----------

def test_fact_sales_totals(fact_sales, kpi_report):
    k = kpi_report.loc["All time"]
    assert len(fact_sales) == 1_021_272                        # product rows, notebook 03
    sales = fact_sales[~fact_sales["is_cancelled"]]
    assert fact_sales["line_revenue"].sum() == pytest.approx(k["net_revenue"], abs=1)
    assert sales["line_revenue"].sum() == pytest.approx(k["gross_revenue"], abs=1)
    assert fact_sales.loc[fact_sales["is_cancelled"], "line_revenue"].sum() == pytest.approx(k["cancellations"], abs=1)
    orders = sales.loc[~sales["is_fully_cancelled_order"], "invoice"]
    assert orders.nunique() == k["orders"]
    assert sales.loc[sales["is_fully_cancelled_order"], "invoice"].nunique() == k["fully_cancelled_orders"]
    assert sales["customer_id"].nunique() == k["customers"]
    aov = sales.loc[~sales["is_fully_cancelled_order"], "line_revenue"].sum() / orders.nunique()
    assert aov == pytest.approx(k["avg_order_value"], abs=0.01)


def test_fact_sales_flags_are_consistent(fact_sales):
    assert (fact_sales["has_customer"] == fact_sales["customer_id"].notna()).all()
    assert (fact_sales["is_cancelled"] == fact_sales["invoice"].str.startswith("C")).all()
    assert not (fact_sales["is_cancelled"] & fact_sales["is_fully_cancelled_order"]).any()


# ---------- monthly_kpis ----------

def test_monthly_kpis_add_up_to_all_time(monthly, kpi_report):
    k = kpi_report.loc["All time"]
    assert len(monthly) == 25                                  # Dec 2009 to Dec 2011
    for col in ["net_revenue", "gross_revenue", "cancellations"]:
        assert monthly[col].sum() == pytest.approx(k[col], abs=1)
    for col in ["orders", "fully_cancelled_orders"]:
        assert monthly[col].sum() == k[col]


def test_monthly_kpis_partial_month(monthly):
    partial = monthly[monthly["is_partial_month"]]
    assert list(partial["month"]) == [pd.Timestamp("2011-12-01")]
    assert partial["mom_growth_pct"].isna().all()
    assert (monthly["net_revenue"] - monthly["gross_revenue"] - monthly["cancellations"]).abs().max() < 0.01


# ---------- cohort_retention ----------

def test_cohort_retention_matches_report(cohort_report):
    long = read_export("cohort_retention", parse_dates=["cohort"])
    assert len(long) == 24 * 24                               # every cohort x month, empty cells as NaN
    assert long["retention_pct"].notna().sum() == cohort_report.notna().sum().sum()
    assert (long.loc[long["month_index"] == 0, "retention_pct"] == 100).all()
    wide = long.pivot(index="cohort", columns="month_index", values="retention_pct")
    wide.columns.name = None
    pd.testing.assert_frame_equal(wide.round(2), cohort_report, atol=0.005, check_freq=False,
                                  check_column_type=False, check_index_type=False)
    assert long.groupby("cohort")["cohort_size"].nunique().eq(1).all()


# ---------- rfm_customers and segment_summary ----------

def test_rfm_customers(rfm_customers):
    assert len(rfm_customers) == 5_832
    assert rfm_customers["customer_id"].is_unique
    for col in ["R_score", "F_score", "M_score"]:
        assert rfm_customers[col].between(1, 5).all()
    assert set(rfm_customers["segment"]) == set(an.SEGMENT_ORDER)
    assert (rfm_customers["net_revenue"] > 0).all()


def test_segment_summary_matches_rfm_customers(segments, rfm_customers):
    assert list(segments["segment"]) == an.SEGMENT_ORDER
    by_segment = rfm_customers.groupby("segment")
    s = segments.set_index("segment")
    pd.testing.assert_series_equal(s["customers"], by_segment.size().reindex(s.index), check_names=False)
    pd.testing.assert_series_equal(s["revenue"], by_segment["net_revenue"].sum().reindex(s.index),
                                   check_names=False, atol=0.01)
    assert s["customers"].sum() == len(rfm_customers)
    assert s["customers_pct"].sum() == pytest.approx(100, abs=0.001)
    assert s["revenue_pct"].sum() == pytest.approx(100, abs=0.001)


def test_segment_summary_matches_recomputed_analysis(segments, rfm):
    expected = an.segment_summary(rfm).reset_index()
    expected["segment"] = expected["segment"].astype(str)
    pd.testing.assert_frame_equal(segments, expected, atol=1e-4, check_dtype=False)


def test_monthly_kpis_match_recomputed_analysis(monthly, products, fully_cancelled):
    expected = an.monthly_kpis(products, exclude_orders=fully_cancelled)
    pd.testing.assert_frame_equal(monthly, expected, atol=1e-4, check_dtype=False)
